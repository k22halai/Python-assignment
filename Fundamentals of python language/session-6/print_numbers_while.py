# task - 1: Print Numbers 1 to 10 (while loop)

print("=" * 40)
print("       NUMBERS 1 TO 10 (WHILE LOOP)     ")
print("=" * 40)

# Initializing counter variable
number = 1

# While loop running until number reaches 10
while number <= 10:
    print(number)
    number += 1  # Increment counter

print("=" * 40)
