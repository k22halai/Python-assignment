# task - 3: Favorite Movies in Uppercase (for loop & .upper())

# Creating list of three favorite movies
fav_movies = [
    "Inception",
    "Interstellar",
    "The Dark Knight"
]

print("=" * 45)
print("         FAVORITE MOVIES (UPPERCASE)          ")
print("=" * 45)

# Iterating through the list and printing each movie in uppercase
for movie in fav_movies:
    print(movie.upper())

print("=" * 45)
